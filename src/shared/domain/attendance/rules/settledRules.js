import { getAttendanceStatus, ATTENDANCE_STATUS } from "../getAttendanceStatus";

// ?????????????????????????????????????????????
// PAY RULE ( ? ??)
// ?????????????????????????????????????????????
export function isPaySettled(row) {
  if (!row) return false;
  const s = row.approval_status;
  return s !== "pending" && s !== "rejected";
}

// ?????????????????????????????????????????????
// UI RULE (? ?)
// ?????????????????????????????????????????????
export function isUISettled(row) {
  const status = getAttendanceStatus(row);
  return (
    status === ATTENDANCE_STATUS.APPROVED ||
    status === ATTENDANCE_STATUS.CLOSED
  );
}

// ?????????????????????????????????????????????
// STATUS RULE ( ? ?)
// ?????????????????????????????????????????????
export function isStatusSettled(row) {
  return getAttendanceStatus(row) === ATTENDANCE_STATUS.APPROVED;
}

// ?????????????????????????????????????????????
// EXPORT GROUP
// ?????????????????????????????????????????????
export const SETTLED_RULES = {
  PAY: isPaySettled,
  UI: isUISettled,
  STATUS: isStatusSettled,
};

// ?????????????????????????????????????????????
// FILTER HELPERS
// ?????????????????????????????????????????????
export const filterPaySettled = (rows = []) =>
  rows.filter(isPaySettled);

export const filterUISettled = (rows = []) =>
  rows.filter(isUISettled);

